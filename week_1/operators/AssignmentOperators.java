package week_1.operators;

public class AssignmentOperators {
    public static void main(String[] args) {
        int a = 19, b = 12;
        a += b;
        System.out.println(a);
        a -= b;
        System.out.println(a);
        a /= b;
        System.out.println(a);
        a *= b;
        System.out.println(a);
        a %= b;
        System.out.println(a);
        a ^= b;
        System.out.println(a);
        a >>= b;
        System.out.println(a);
        a <<= b;
        System.out.println(a);
        a >>>= b;
        System.out.println(a);
    }
}
