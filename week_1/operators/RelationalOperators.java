package week_1.operators;

public class RelationalOperators {
    /**
     * @param args
     * always return boolean value
     */
    public static void main(String[] args) {
        int a, b;
        a = b = 10;
        int c = 17;
        System.out.println(a == b); //true
        System.out.println(a != b); //false
        System.out.println(a > b); //false
        System.out.println(a >= b); // true
        System.out.println(a < b); // false
        System.out.println(a <= b); // true
    }
}
